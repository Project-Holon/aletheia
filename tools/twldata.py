#!/usr/bin/env python3
"""twldata.py: the data of the DSi block (region twl) as typed C, from the user's own extract.

The twl block (arm9i.bin, 0x02700000..0x02732DA0) is linked from src/game/twl by tools/twllink.py.
Four byte ranges lie between the files of that link (datareg.TWL_RANGES): the embedded DSP component,
a pointer table of mi_sharedWram.c, the strings and one variable of the DSP files, and the zero
padding up to the bss.  This tool turns the objects of layout/data_objects.json (key twl_data: address,
size, kind, name, owner file; no values) into companion files, the way tools/datagen.py does it for the
overlays and tools/arm9data.py for the ARM9:

    python tools/twldata.py                  # Black: build/datac/twl/*.c
    python tools/twldata.py --version white  # Black's structure, White's values: build/datac_white/twl/*.c
    python tools/twldata.py --dry-run        # list the files and sizes, write nothing
    python tools/twldata.py --check          # write, link with tools/twllink.py, require PASS and no gap

One companion per object: <owner>.zdata.c (a second object of the same owner:
<owner>.zdata_2.c, ...); an object with no owner is named after itself (the padding).  Each file has the header the plain-mode
link of tools/gamelink.py reads (address, symbols: the name of every object at its address), so the
section lands where the original has it.  The initialiser values come from the image at run time and
are written to build/ only (gitignored); nothing generated is committed.  tools/twllink.py calls
this module unless it runs with --image-gaps.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import datareg    # noqa: E402
import datagen    # noqa: E402

HEADER = """/*
 * file:     %(stem)s.c
 * address:  0x%(addr)08X
 * region:   twl
 * compiler: dsi/1.1p1
 * flags:    -O4,p
 * lang:     c99
 * isa:      arm
 * status:   EXACT
 *
 * symbols:
%(syms)s */
/* data of the DSi block that no src/game/twl file writes; generated by tools/twldata.py from the
 * local extract into build/ (never committed) */
"""


def out_dir(white):
    return os.path.join(ROOT, "build", "datac_white" if white else "datac", "twl")


def twl_image(white):
    """(base, image) of the twl block: Black from layout/extract, White from extract_white/."""
    import twllink
    return twllink.twl_block(white)


def groups(objs):
    """[(file stem, [object])]: one file per object.  The compiler orders the objects of one
    section by its own rules, so two objects in one file would not keep their addresses."""
    out = []
    count = {}
    for o in sorted(objs, key=lambda o: int(o["addr"], 16)):
        ow = o.get("owner")
        if ow:
            count[ow] = count.get(ow, 0) + 1
            stem = "%s.zdata%s" % (ow, "" if count[ow] == 1 else "_%d" % count[ow])
        else:
            stem = o["name"]
        out.append((stem, [o]))
    return out


def build(white=False, dry=False):
    """Write the companions; -> list of (file, bytes of data, object count)."""
    reg = datagen.load_registry().get(datareg.REG_KEY["twl"])
    if reg is None:
        raise SystemExit("layout/data_objects.json has no region twl_data: run tools/datareg.py --region twl")
    base, img = twl_image(white)
    if white:
        b_base, b_img = twl_image(False)
        if (b_base, len(b_img)) != (base, len(img)):
            raise SystemExit("the twl block of White differs in place or size from Black's")
    d = out_dir(white)
    if not dry:
        os.makedirs(d, exist_ok=True)
        for f in os.listdir(d):
            if f.endswith(".c"):
                os.remove(os.path.join(d, f))
    res = []
    for stem, objs in groups(reg["objects"]):
        a0 = int(objs[0]["addr"], 16)
        syms = "".join(" *   %s  0x%08X  data twl\n" % (o["name"], int(o["addr"], 16)) for o in objs)
        # an all-zero array would go to .bss, which the link counts as a stand-in: write it as bytes,
        # const so that it stays in .rodata
        zero = [o["name"] for o in objs if o["kind"] == "zero"]
        objs = [dict(o, kind="raw") if o["kind"] == "zero" else o for o in objs]
        sub = dict(reg, objects=objs)
        text = datagen.Gen("twl", sub, img, base).emit()
        for n in zero:
            text = text.replace("unsigned char %s[" % n, "const unsigned char %s[" % n)
        text = HEADER % dict(stem=stem, addr=a0, syms=syms) + text
        size = sum(o["size"] for o in objs)
        res.append((stem + ".c", size, len(objs)))
        if not dry:
            with open(os.path.join(d, stem + ".c"), "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
    return res


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--version", choices=("black", "white"), default="black")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    white = a.version == "white"
    res = build(white, a.dry_run)
    where = os.path.relpath(out_dir(white), ROOT).replace(os.sep, "/")
    for f, size, n in res:
        print("%s/%s  %d bytes, %d objects" % (where, f, size, n))
    print("twl data: %d files, %d bytes%s" % (len(res), sum(r[1] for r in res), " (dry run)" if a.dry_run else ""))
    if a.check and not a.dry_run:
        import twllink
        rc = twllink.main(["--version=white"] if white else [])
        j = json.load(open(os.path.join(ROOT, "build", "gamelink", "twl_white" if white else "twl", "ov.json")))
        if j.get("gaps"):
            print("twl FAIL: gaps left: %s" % j["gaps"])
            return 1
        return rc
    return 0


if __name__ == "__main__":
    sys.exit(main())
