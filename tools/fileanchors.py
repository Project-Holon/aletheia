#!/usr/bin/env python3
"""fileanchors.py -- harvest __FILE__ pool anchors across the whole image.

A CodeWarrior/MSL assert or panic macro embeds a ``__FILE__`` argument as a
literal pool word: the compiler emits a NUL-terminated copy of the source
path into its object's string area and loads a pointer to it through
``ldr rX, [pc, #n]`` like any other pooled constant (see
docs/idioms/file-string-is-an-abs32-into-the-string-area.md). Those pool
words are a free, compiler-generated attestation of which translation unit a
block of code came from, so collecting every one of them image-wide gives a
name-guessing tool something concrete to work from.

This reuses tools/disasm.py's own region model and trace (the same code that
produces asm/arm9/*.s and asm/overlays/*.s) rather than re-deriving pool
classification from the text listings: a "pool word" here means exactly what
disasm.py already proved is a literal pool entry reached by a PC-relative
load from traced code, not a coincidental data word. For each such word we
check whether the address it holds names a NUL-terminated, all-printable
ASCII run in the data segment (of the same family of regions: the ARM9
static image plus its autoloads share one family, and each overlay is its
own) whose text ends in ``.c`` or ``.cpp``.

Nothing here reads or writes game data beyond the file paths themselves:
output is addresses and .c/.cpp file names only, the same discipline
layout/symbols_sdk.txt follows.

Usage
-----
    python tools/fileanchors.py                scan the whole image, write
                                                 layout/file_anchors.txt
    python tools/fileanchors.py --summary       counts per region (reads the
                                                 committed file if present,
                                                 otherwise scans first)
    python tools/fileanchors.py --lookup ADDR   nearest anchor at or below
                                                 ADDR in the same region

Output
------
    layout/file_anchors.txt   one line per anchor: pool site address,
                               owning function address, region, string
                               address, file name
"""

from __future__ import annotations

import argparse
import bisect
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))

import disasm  # noqa: E402

OUT_PATH = os.path.join(ROOT, "layout", "file_anchors.txt")

MAX_STRING_LEN = 260
STRING_SUFFIXES = (".c", ".cpp")

HEADER = [
    "# __FILE__ pool anchors harvested from the ARM9 static image and all overlays",
    "# addresses and file names only; contains no other game data",
    "# generated by tools/fileanchors.py; do not edit, do not commit game bytes",
    "# columns: pool_site  function  region  string_addr  filename",
]


class Anchor(object):
    __slots__ = ("pool_site", "func", "region", "str_addr", "name")

    def __init__(self, pool_site, func, region, str_addr, name):
        self.pool_site = pool_site
        self.func = func
        self.region = region
        self.str_addr = str_addr
        self.name = name


# ---------------------------------------------------------------- scanning


def _extract_c_string(data, off):
    """A printable, NUL-terminated run at ``off`` ending in .c/.cpp, or None."""
    n = len(data)
    if off < 0 or off >= n:
        return None
    end = off
    while end < n and 0x20 <= data[end] < 0x7F:
        end += 1
        if end - off > MAX_STRING_LEN:
            return None
    if end == off or end >= n or data[end] != 0:
        return None
    text = data[off:end].decode("ascii")
    if not text.endswith(STRING_SUFFIXES):
        return None
    return text


def _owning_function(sorted_funcs, addr):
    i = bisect.bisect_right(sorted_funcs, addr) - 1
    if i < 0:
        return None
    return sorted_funcs[i]


def _scan_family(regions):
    """Anchors found by tracing every region in ``regions`` as one family.

    A pool word's string is looked up first in the region the pool site
    itself lives in (the overwhelmingly common case: one translation unit's
    __FILE__ points into that same unit's string area), then in every other
    region of the same family (so an ARM9 autoload block referencing a
    string packed into the static module's data is still caught).
    """
    anchors = []
    for r in regions:
        disasm.Analyser(r).run()

    for r in regions:
        sorted_funcs = sorted(r.funcs)
        for pool_addr, width in sorted(r.pools.items()):
            if width != 4:
                continue
            value = r.word(pool_addr)
            if value is None:
                continue
            text = None
            str_region = None
            for cand in [r] + [o for o in regions if o is not r]:
                off = value - cand.base
                found = _extract_c_string(cand.data, off)
                if found is not None:
                    text = found
                    str_region = cand
                    break
            if text is None:
                continue
            func = _owning_function(sorted_funcs, pool_addr)
            anchors.append(Anchor(pool_addr, func, r.name, value, text))
    return anchors


def scan_all(layout, extract_dir, layout_dir):
    anchors = []

    arm9_regions = disasm.build_arm9_regions(layout, extract_dir, layout_dir)
    anchors.extend(_scan_family(arm9_regions))

    for ov_id in range(len(layout["overlays"])):
        r = disasm.build_overlay_region(layout, extract_dir, ov_id, layout_dir)
        anchors.extend(_scan_family([r]))

    anchors.sort(key=lambda a: (a.region, a.pool_site))
    return anchors


# ---------------------------------------------------------------- file I/O


def write_anchors(anchors, path=OUT_PATH):
    lines = list(HEADER)
    for a in anchors:
        func_field = "%08X" % a.func if a.func is not None else "--------"
        lines.append(
            "%08X  %s  %-24s %08X  %s"
            % (a.pool_site, func_field, a.region, a.str_addr, a.name)
        )
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def read_anchors(path=OUT_PATH):
    anchors = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            parts = line.split(None, 4)
            if len(parts) != 5:
                continue
            pool_site_s, func_s, region, str_addr_s, name = parts
            func = None if func_s == "--------" else int(func_s, 16)
            anchors.append(
                Anchor(int(pool_site_s, 16), func, region,
                       int(str_addr_s, 16), name)
            )
    return anchors


def load_or_scan(args):
    if os.path.isfile(OUT_PATH) and not getattr(args, "force", False):
        return read_anchors()
    layout = disasm.load_layout(args.layout)
    anchors = scan_all(layout, args.extract, args.layout)
    write_anchors(anchors)
    return anchors


# ---------------------------------------------------------------- region resolution


def resolve_region(addr, layout, extract_dir, layout_dir):
    """The region name owning ``addr``, or None."""
    for r in disasm.build_arm9_regions(layout, extract_dir, layout_dir):
        if r.contains(addr):
            return r.name
    for i, o in enumerate(layout["overlays"]):
        lo, hi = o["ram_start"], o["ram_start"] + o["code_size"]
        if lo <= addr < hi:
            return "overlay_%03d" % i
    return None


# ---------------------------------------------------------------- commands


def cmd_summary(anchors):
    by_region = {}
    for a in anchors:
        by_region[a.region] = by_region.get(a.region, 0) + 1
    print("file anchors: %d total across %d region(s)"
          % (len(anchors), len(by_region)))
    for region in sorted(by_region):
        print("  %-24s %5d" % (region, by_region[region]))
    return 0


def cmd_lookup(anchors, addr, layout, extract_dir, layout_dir):
    region = resolve_region(addr, layout, extract_dir, layout_dir)
    if region is None:
        print("0x%08X is not inside any known region" % addr, file=sys.stderr)
        return 1
    candidates = sorted(
        (a for a in anchors if a.region == region and a.pool_site <= addr),
        key=lambda a: a.pool_site,
    )
    if not candidates:
        print("no anchor at or below 0x%08X in region %s" % (addr, region))
        return 1
    a = candidates[-1]
    func_field = "%08X" % a.func if a.func is not None else "--------"
    print("0x%08X  region %s" % (addr, region))
    print("  nearest anchor: pool_site 0x%08X  function 0x%s  "
          "string 0x%08X  %s  (distance 0x%X)"
          % (a.pool_site, func_field, a.str_addr, a.name, addr - a.pool_site))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="harvest __FILE__ literal-pool anchors across the "
                    "ARM9 static image and all overlays")
    ap.add_argument("-e", "--extract", default="extract")
    ap.add_argument("-l", "--layout", default="layout")
    ap.add_argument("--summary", action="store_true",
                    help="print counts per region and exit")
    ap.add_argument("--lookup", metavar="ADDR",
                    help="nearest anchor at or below ADDR in the same region")
    ap.add_argument("--force", action="store_true",
                    help="rescan the image even if layout/file_anchors.txt "
                         "already exists")
    args = ap.parse_args(argv)

    if args.lookup is not None:
        try:
            addr = int(args.lookup, 0)
        except ValueError:
            print("bad address: %s" % args.lookup, file=sys.stderr)
            return 2
        anchors = load_or_scan(args)
        layout = disasm.load_layout(args.layout)
        return cmd_lookup(anchors, addr, layout, args.extract, args.layout)

    if args.summary:
        anchors = load_or_scan(args)
        return cmd_summary(anchors)

    layout = disasm.load_layout(args.layout)
    anchors = scan_all(layout, args.extract, args.layout)
    write_anchors(anchors)
    print("wrote %s: %d anchor(s)"
          % (os.path.relpath(OUT_PATH, ROOT), len(anchors)))
    return cmd_summary(anchors)


if __name__ == "__main__":
    sys.exit(main())
