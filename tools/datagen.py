#!/usr/bin/env python3
"""datagen.py: typed C for data objects, generated from the user's own ROM.

Reads layout/data_objects.json (addresses, sizes, kinds, names: no values) and
the user's extracted image (extract/, the same source build.py uses) and
writes one C file per region into build/data/ (gitignored).  The initialiser
values come from the image at run time; nothing generated is committed.

  python tools/datagen.py gen   [--region arm9 ...]   write build/data/<region>_data.c
  python tools/datagen.py check [--region arm9 ...]   gen + compile with mwccarm + compare
                                                      every object with the image
  python tools/datagen.py companions 12 [--out=DIR]   companion files <stem>.zdata.c for
                                                      tools/gamelink.py --data (see below)

Pointers are written as (char *)&name + addend where name is the registry name
of the target (a defined object of the same file, or an extern from the
registry's "externs" list); addend 1 encodes a Thumb entry bit.  Regions are
arm9 and every overlay ovNNN of the registry; without --region all of them run
and check prints a total (exit status 1 if any object differs).
"""
